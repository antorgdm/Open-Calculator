    fun convert(amount: Double, from: CurrencyItem, to: CurrencyItem): Double {
        if (from.code == to.code) return amount
        val amountInUsd = amount / from.rateToUsd
        return amountInUsd * to.rateToUsd
    }

    fun formatAmount(amount: Double): String {
        if (amount.isNaN() || amount.isInfinite()) return "-"
        val df = when {
            amount >= 1000 -> DecimalFormat("#,##0.00")
            amount >= 1 -> DecimalFormat("#,##0.00")
            else -> DecimalFormat("#,##0.0000")
        }
        return df.format(amount)
    }

    fun searchCurrencies(query: String): List<CurrencyItem> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return allCurrencies
        return allCurrencies.filter {
            it.code.lowercase().contains(q) ||
            it.name.lowercase().contains(q) ||
            it.country.lowercase().contains(q) ||
            it.symbol.lowercase().contains(q)
        }
    }
